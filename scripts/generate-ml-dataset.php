// ========== EXTRA SEARCH: combinations ==========
$extraSearchCombos = [
    ['отель {city} {amenity}', ['city', 'amenity']],
    ['{city} {stars} звёзд', ['city', 'stars']],
    ['{city} на {guests} человек', ['city', 'guests']],
    ['{city} до {price}', ['city', 'price']],
    ['{amenity} в {city}', ['amenity', 'city']],
    ['{stars} звёзд {amenity}', ['stars', 'amenity']],
    ['{guests} человек {city} {amenity}', ['guests', 'city', 'amenity']],
    ['{city} {stars} звёзд {amenity}', ['city', 'stars', 'amenity']],
    ['{city} на {guests} с {amenity}', ['city', 'guests', 'amenity']],
    ['{city} {stars} на {guests}', ['city', 'stars', 'guests']],
];

$extraPrices = [3000, 5000, 7000, 8000, 10000, 12000, 15000, 20000, 25000, 30000, 40000, 50000, 70000, 100000, 120000, 150000];
$extraGuests = [1, 2, 3, 4, 5, 6, 8, 10];
$extraStars = [2, 3, 4, 5];

for ($i = 0; $i < 500; $i++) {
    $tpl = pick($extraSearchCombos);
    $t = $tpl[0];
    $city = pick($cities);
    $forms = $cityForms[$city] ?? [$city];
    $cityForm = pick($forms);
    $amenity = pick($amenities);
    $stars = pick($extraStars);
    $guests = pick($extraGuests);
    $price = pick($extraPrices);
    $t = str_replace('{city}', $cityForm, $t);
    $t = str_replace('{amenity}', $amenity, $t);
    $t = str_replace('{stars}', (string)$stars, $t);
    $t = str_replace('{guests}', (string)$guests, $t);
    $t = str_replace('{price}', (string)$price, $t);
    $ents = ['city' => $city];
    if ($tpl[1] && in_array('amenity', $tpl[1])) $ents['amenities'] = [$amenity];
    if ($tpl[1] && in_array('stars', $tpl[1])) $ents['stars'] = $stars;
    if ($tpl[1] && in_array('guests', $tpl[1])) $ents['guests'] = $guests;
    if ($tpl[1] && in_array('price', $tpl[1])) $ents['price_max'] = $price;
    addPhrase('search', $t, $ents);
}

